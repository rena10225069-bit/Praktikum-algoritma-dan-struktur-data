# Program Rekap Nilai Mahasiswa

# Data mahasiswa pertama
nama = "Rena"
nilai_tugas = 80
nilai_ujian = 90

# Menghitung rata-rata
rata_rata = (nilai_tugas + nilai_ujian) / 2

# Memeriksa status kelulusan
lulus = rata_rata >= 75

# Menampilkan hasil mahasiswa pertama
print("=== Rekap Nilai Mahasiswa 1 ===")
print("Nama          :", nama)
print("Nilai Tugas   :", nilai_tugas)
print("Nilai Ujian   :", nilai_ujian)
print("Rata-rata     :", rata_rata)
print("Status Lulus  :", lulus)

