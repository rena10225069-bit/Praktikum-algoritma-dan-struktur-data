# 1. Membuat variabel harga dan jumlah
harga = 12500
jumlah = 4

# 2. Menghitung total harga
total_harga = harga * jumlah

# 3. Menghitung sisa pembagian dengan operator %
sisa_pembagian = total_harga % 2000

# 4. Menghitung harga setelah diskon Rp5.000
diskon = 5000
harga_setelah_diskon = total_harga - diskon

# 5. Menampilkan hasil perhitungan
print("Harga buku per buah: Rp", harga)
print("Jumlah buku yang dibeli:", jumlah, "buah")
print("Total harga: Rp", total_harga)
print("Sisa pembagian total harga dengan 2.000: Rp", sisa_pembagian)
print("Diskon: Rp", diskon)
print("Harga setelah diskon: Rp", harga_setelah_diskon)