# 1. Menyimpan poin awal
poin = 100
print("Poin awal:", poin)

# 2. Menambahkan 25 poin menggunakan +=
poin += 25
print("Setelah ditambah 25:", poin)

# 3. Mengurangi 10 poin menggunakan -=
poin -= 10
print("Setelah dikurangi 10:", poin)

# 4. Mengalikan poin dengan 2 menggunakan *=
poin *= 2
print("Setelah dikalikan 2:", poin)

# 5. Membagi poin dengan 2 menggunakan /=
poin /= 2
print("Setelah dibagi 2:", poin)